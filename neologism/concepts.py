"""Concept definitions.

Each concept supplies (a) the instruction suffix used to *generate* chosen
(concept-bearing) responses from the base model, (b) a neutral word whose
embedding initializes the neologism (paper Sec 4.1), and (c) a programmatic
metric so we can measure how strongly a response exhibits the concept
(reproducing the count metrics in Table 1 of the paper).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Callable


def _count_sentences(text: str) -> float:
    text = text.strip()
    if not text:
        return 0.0
    # Count sentence-terminating punctuation groups.
    parts = re.findall(r"[^.!?]+[.!?]+", text)
    n = len(parts)
    # account for a trailing fragment with no terminal punctuation
    tail = re.sub(r"[^.!?]+[.!?]+", "", text).strip()
    if tail:
        n += 1
    return float(max(n, 1))


def _count_words(text: str) -> float:
    return float(len(text.split()))


def _like_prevalence(text: str) -> float:
    words = re.findall(r"[a-zA-Z']+", text.lower())
    if not words:
        return 0.0
    return 100.0 * sum(w == "like" for w in words) / len(words)


def _starts_with_to(text: str) -> float:
    return 1.0 if text.strip().startswith("To") else 0.0


def _starts_with_okay(text: str) -> float:
    return 1.0 if text.strip().lower().startswith("okay") else 0.0


def _starts_with_the(text: str) -> float:
    return 1.0 if text.strip().startswith("The") else 0.0


@dataclass
class Concept:
    name: str
    # suffix appended to the raw instruction to elicit a chosen response
    gen_suffix: str
    # neutral word used to initialize the neologism embedding
    init_word: str
    # programmatic metric over a response string
    metric: Callable[[str], float]
    # True if a higher metric means "more of the concept"
    higher_is_more: bool
    metric_name: str
    # Optional: instead of eliciting chosen responses with `gen_suffix`, seed the
    # assistant turn with these prefixes (used for concepts about how a response
    # *begins*, e.g. forcing a reasoning model's chain-of-thought to start with
    # a given word). When `chosen_prefix` is set, gen_suffix is ignored.
    chosen_prefix: str | None = None
    rejected_prefix: str | None = None
    # Whether to append EOS to chosen responses during training. For reasoning
    # traces we set this False so we only steer the *opening* and never teach the
    # frozen model to stop early.
    append_eos: bool = True


CONCEPTS: dict[str, Concept] = {
    "single-sentence": Concept(
        name="single-sentence",
        gen_suffix=(
            "Answer in a single sentence. Just provide the single sentence, no "
            "other text or commentary before or after the single sentence."
        ),
        init_word=" accurate",
        metric=_count_sentences,
        higher_is_more=False,
        metric_name="sentence_count",
    ),
    "short-text": Concept(
        name="short-text",
        gen_suffix="Be as concise as possible.",
        init_word=" accurate",
        metric=_count_words,
        higher_is_more=False,
        metric_name="word_count",
    ),
    "long-text": Concept(
        name="long-text",
        gen_suffix="Be as verbose as possible.",
        init_word=" accurate",
        metric=_count_words,
        higher_is_more=True,
        metric_name="word_count",
    ),
    "use-like": Concept(
        name="use-like",
        gen_suffix="In your answer, use the word 'like' as much as possible.",
        init_word=" single",
        metric=_like_prevalence,
        higher_is_more=True,
        metric_name="like_prevalence_pct",
    ),
    # For reasoning models (e.g. DeepSeek-R1-Distill): make the chain-of-thought
    # begin with "To ..." instead of the model's default "Okay, ...". Chosen
    # traces are generated by seeding the <think> block with "To"; the rejected
    # set uses the default opening.
    "to-thinking": Concept(
        name="to-thinking",
        gen_suffix="",  # unused; we seed the assistant turn instead
        init_word="<<random>>",
        metric=_starts_with_to,
        higher_is_more=True,
        metric_name="thinking_starts_with_To",
        chosen_prefix="To",
        rejected_prefix=None,  # default behavior
        append_eos=False,
    ),
    # Same idea, but the chain-of-thought begins with "Okay ..." — note this is
    # the R1-Distill *default* opening, so the neologism is taught to reproduce
    # behavior the base model already exhibits.
    "okay-thinking": Concept(
        name="okay-thinking",
        gen_suffix="",
        init_word="<<random>>",
        metric=_starts_with_okay,
        higher_is_more=True,
        metric_name="thinking_starts_with_Okay",
        chosen_prefix="Okay",
        rejected_prefix=None,
        append_eos=False,
    ),
    # Same idea as to-thinking, but the chain-of-thought begins with "The ...".
    "the-thinking": Concept(
        name="the-thinking",
        gen_suffix="",
        init_word="<<random>>",
        metric=_starts_with_the,
        higher_is_more=True,
        metric_name="thinking_starts_with_The",
        chosen_prefix="The",
        rejected_prefix=None,
        append_eos=False,
    ),
}


def get_concept(name: str) -> Concept:
    if name not in CONCEPTS:
        raise KeyError(f"Unknown concept {name!r}. Choices: {list(CONCEPTS)}")
    return CONCEPTS[name]
